// Builds src/sections/registry.generated.ts: every src/sections/<type>.tsx becomes section type "<type>".
// Run after adding a section: node scripts/build-registry.mjs
import fs from 'node:fs';
const files = fs.readdirSync('src/sections').filter((f) => /^[a-z0-9-]+\.tsx$/.test(f)).sort();
const ident = (f) => f.replace('.tsx', '').replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const out =
  `// Generated by scripts/build-registry.mjs. Do not edit by hand.\n` +
  `/* eslint-disable @typescript-eslint/no-explicit-any */\n` +
  files.map((f) => `import ${ident(f)} from './${f.replace('.tsx', '')}';`).join('\n') +
  `\n\nexport const registry: Record<string, (props: any) => any> = {\n` +
  files.map((f) => `  '${f.replace('.tsx', '')}': ${ident(f)},`).join('\n') +
  `\n};\n`;
fs.writeFileSync('src/sections/registry.generated.ts', out);
console.log('sections:', files.map((f) => f.replace('.tsx', '')).join(', ') || '(none)');
